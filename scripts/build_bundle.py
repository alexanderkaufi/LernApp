#!/usr/bin/env python3
"""
Builds LernApp/app.bundle.js as a single classic-script IIFE from app.js and its ES modules.
Used automatically when index.html is opened directly via file:// where browsers block ES modules.
"""

from __future__ import annotations

import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRY = ROOT / "app.js"
OUTPUT = ROOT / "app.bundle.js"

IMPORT_RE = re.compile(
    r"""^\s*import\s+(?:[\s\S]*?\s+from\s+)?['"]([^'"]+)['"]\s*;?[ \t]*$""",
    re.MULTILINE,
)
REEXPORT_RE = re.compile(
    r"""^\s*export\s*\{[^}]*\}\s*(?:from\s*['"][^'"]+['"])?\s*;?[ \t]*$""",
    re.MULTILINE,
)
EXPORT_DECL_RE = re.compile(
    r"""^export\s+(?=(?:async\s+)?function\b|const\b|let\b|var\b|class\b)""",
    re.MULTILINE,
)
TOP_DECL_RE = re.compile(
    r"""^(?:export\s+)?(?:const|let|var|async\s+function|function|class)\s+([A-Za-z_$][A-Za-z0-9_$]*)"""
)


def resolve_module_order(entry: pathlib.Path) -> list[pathlib.Path]:
    """Returns modules topologically sorted (dependencies before dependents)."""
    visited: set[pathlib.Path] = set()
    visiting: set[pathlib.Path] = set()
    ordered: list[pathlib.Path] = []

    def visit(path: pathlib.Path) -> None:
        resolved = path.resolve()
        if resolved in visited:
            return
        if resolved in visiting:
            raise RuntimeError(f"Cyclic ES module import involving {resolved}")
        visiting.add(resolved)

        text = resolved.read_text(encoding="utf-8")
        for match in IMPORT_RE.finditer(text):
            dep = (resolved.parent / match.group(1)).resolve()
            if not dep.exists():
                raise FileNotFoundError(f"Missing import {match.group(1)} in {resolved}")
            visit(dep)

        visiting.remove(resolved)
        visited.add(resolved)
        ordered.append(resolved)

    visit(entry)
    return ordered


def extract_import_aliases(source: str) -> list[tuple[str, str]]:
    """Extracts any `original as alias` pairs from ES import blocks."""
    aliases: list[tuple[str, str]] = []
    for match in IMPORT_RE.finditer(source):
        stmt = match.group(0)
        brace_match = re.search(r"\{([^}]*)\}", stmt)
        if not brace_match:
            continue
        for item in brace_match.group(1).split(","):
            part = item.strip()
            if not part or " as " not in part:
                continue
            orig, alias = (segment.strip() for segment in part.split(" as ", 1))
            if orig and alias and orig != alias:
                aliases.append((orig, alias))
    return aliases


def strip_module_syntax(source: str) -> str:
    """Converts an ES module into plain statements suitable for an IIFE body."""
    aliases = extract_import_aliases(source)
    alias_lines = "".join(f"const {alias} = {orig};\n" for orig, alias in aliases)
    cleaned = IMPORT_RE.sub("", source)
    cleaned = REEXPORT_RE.sub("", cleaned)
    cleaned = EXPORT_DECL_RE.sub("", cleaned)
    return alias_lines + cleaned.strip() + "\n"


def check_unique_top_level_symbols(modules: list[pathlib.Path]) -> None:
    """Ensures concatenating modules into a single IIFE scope causes no identifier clashes."""
    seen: dict[str, list[str]] = defaultdict(list)
    for mod in modules:
        rel = mod.relative_to(ROOT).as_posix()
        text = mod.read_text(encoding="utf-8")
        for lineno, line in enumerate(text.splitlines(), 1):
            match = TOP_DECL_RE.match(line)
            if match:
                seen[match.group(1)].append(f"{rel}:{lineno}")
        for _, alias in extract_import_aliases(text):
            seen[alias].append(f"{rel}:alias")

    collisions = {name: locs for name, locs in seen.items() if len(locs) > 1}
    if collisions:
        raise RuntimeError(f"Top-level symbol collisions across modules: {collisions}")


def build_bundle() -> None:
    modules = resolve_module_order(ENTRY)
    check_unique_top_level_symbols(modules)

    sections = [
        "/**",
        " * Auto-generated offline fallback bundle for file:// access.",
        " * Generated by scripts/build_bundle.py from ES modules in data/, src/, and app.js.",
        " */",
        "(() => {",
        "  'use strict';",
        ""
    ]

    for mod in modules:
        rel = mod.relative_to(ROOT).as_posix()
        body = strip_module_syntax(mod.read_text(encoding="utf-8"))
        sections.append(f"  // === Module: {rel} ===")
        sections.append(body)

    sections.append("})();")
    OUTPUT.write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"Built {OUTPUT.relative_to(ROOT.parent)} from {len(modules)} modules ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    build_bundle()
